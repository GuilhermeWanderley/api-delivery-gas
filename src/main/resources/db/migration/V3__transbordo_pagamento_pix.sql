-- V3: atendimento humano (transbordo), status de pagamento, origem do pedido e chave PIX.
-- Compatível com ddl-auto=validate do perfil docker.

-- ---------------------------------------------------------------------------
-- 1) Solicitações de atendimento humano (botão "falar com atendente" / áudio)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transbordos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telefone           VARCHAR(128) NOT NULL,
    nome               VARCHAR(255),
    motivo             VARCHAR(40)  NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    data_criacao       TIMESTAMP    NOT NULL,
    data_atendimento   TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_transbordo_status ON transbordos (status, data_criacao);

-- ---------------------------------------------------------------------------
-- 2) Pedidos: situação do pagamento e origem
-- ---------------------------------------------------------------------------
ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS status_pagamento VARCHAR(30) NOT NULL DEFAULT 'NAO_APLICAVEL';
ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS origem           VARCHAR(10) NOT NULL DEFAULT 'BOT';

-- ---------------------------------------------------------------------------
-- 3) Configuração: chave PIX editável no painel
-- ---------------------------------------------------------------------------
ALTER TABLE configuracoes ADD COLUMN IF NOT EXISTS chave_pix VARCHAR(255);
